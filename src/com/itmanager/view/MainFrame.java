    private void addAssetBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addAssetBtnActionPerformed
        try {
            // 1. Gather input from the user via popup dialogs
            String tag = javax.swing.JOptionPane.showInputDialog(this, "Enter Asset Tag (e.g., LPT-001):");
            if (tag == null || tag.trim().isEmpty()) return; // Cancel if empty

            String type = javax.swing.JOptionPane.showInputDialog(this, "Enter Device Type (e.g., Laptop, Monitor):");
            String model = javax.swing.JOptionPane.showInputDialog(this, "Enter Model Name:");

            // 2. Create the Model object
            com.itmanager.model.Asset newAsset = new com.itmanager.model.Asset(tag, type, model, "Available");

            // 3. Send it to the Database via DAO
            com.itmanager.dao.AssetDAO dao = new com.itmanager.dao.AssetDAO();
            dao.addAsset(newAsset);

            javax.swing.JOptionPane.showMessageDialog(this, "Asset saved to MySQL Database!");    
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error saving asset: " + e.getMessage());
        }
    }//GEN-LAST:event_addAssetBtnActionPerformed

